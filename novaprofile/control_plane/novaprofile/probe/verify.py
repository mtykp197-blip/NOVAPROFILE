def harness_path() -> Path:
    """Return the path of the checked-in verification harness."""

    return VERIFY_HARNESS_PATH


def read_harness_html() -> str:
    """Read the checked-in verification harness from disk."""

    return VERIFY_HARNESS_PATH.read_text(encoding="utf-8")


def report_to_dict(report: VerifyReport) -> dict[str, Any]:
    """Return the JSON-serialisable form of ``report``."""

    return report.to_dict()


