@dataclass(frozen=True)
class FieldVerdict:
    """The verdict of a single field of an axis."""

    field: str
    verdict: str
    expected: Any
    actual: Any
    detail: str = ""

    def to_dict(self) -> dict[str, Any]:
        """Return the JSON-serialisable form of the verdict."""

        return {
            "field": self.field,
            "verdict": self.verdict,
            "expected": _jsonable(self.expected),
            "actual": _jsonable(self.actual),
            "detail": self.detail,
        }


@dataclass(frozen=True)
class AxisResult:
    """The verdict of one axis."""

    axis: str
    verdict: AxisVerdict
    asserted: int
    mismatched: int
    fields: tuple[FieldVerdict, ...] = ()
    profile: Any = None
    browser: Any = None

    @property
    def ok(self) -> bool:
        """Whether the axis matched.

        An ``unavailable`` axis is not a failure: it means the profile
        does not describe the axis or the browser does not expose the
        surface, so there was nothing to compare.

        A ``host-dependent`` axis is not a failure either.  Its values
        come from the machine the browser ran on, so the disagreement
        is between the profile and the verification machine, not
        between the profile and a browser.
        """

        return self.verdict in {"pass", "unavailable", "host-dependent"}

    @property
    def mismatches(self) -> tuple[FieldVerdict, ...]:
        """The fields that disagreed."""

        return tuple(item for item in self.fields if item.verdict == "mismatch")

    def to_dict(self) -> dict[str, Any]:
        """Return the JSON-serialisable form of the result."""

        return {
            "axis": self.axis,
            "verdict": self.verdict,
            "ok": self.ok,
            "asserted": self.asserted,
            "mismatched": self.mismatched,
            "fields": [item.to_dict() for item in self.fields],
            "profile": _jsonable(self.profile),
            "browser": _jsonable(self.browser),
        }


@dataclass
class VerifyReport:
    """The outcome of one verification run."""

    profile_id: str
    passed: bool
    axes: list[AxisResult] = field(default_factory=list)
    browser: str = ""
    browser_version: str = ""
    harness: str = ""
    has_runtime: bool = False
    has_native_core: bool = False
    error: str = ""

    @property
    def verdicts(self) -> dict[str, str]:
        """The verdict of every axis, keyed by axis name."""

        return {item.axis: item.verdict for item in self.axes}

    def counts(self) -> dict[str, int]:
        """The number of axes per verdict."""

        counts = {"pass": 0, "fail": 0, "unavailable": 0, "host-dependent": 0}
        for item in self.axes:
            counts[item.verdict] = counts.get(item.verdict, 0) + 1
        return counts

    def to_dict(self) -> dict[str, Any]:
        """Return the JSON-serialisable form of the report."""

        counts = self.counts()
        # The axes that can be compared are the ones that do not read
        # from the machine the verification ran on.  Those are the ones
        # the pass rate is made of.
        comparable = counts["pass"] + counts["fail"]
        conclusion = (
            f"{counts['pass']}/{comparable} comparable axes match the real "
            f"browser, {counts['fail']} mismatch, "
            f"{counts['host-dependent']} depend on the host machine, "
            f"{counts['unavailable']} unavailable."
        )
        if self.error:
            conclusion = f"The run failed: {self.error}"
        return {
            "slug": "probe-verify",
            "profile_id": self.profile_id,
            "passed": self.passed,
            "browser": self.browser,
            "browser_version": self.browser_version,
            "harness": self.harness,
            "has_runtime": self.has_runtime,
            "has_native_core": self.has_native_core,
            "metrics": {
                "axes_total": len(self.axes),
                "axes_comparable": comparable,
                "axes_pass": counts["pass"],
                "axes_fail": counts["fail"],
                "axes_host_dependent": counts["host-dependent"],
                "axes_unavailable": counts["unavailable"],
                "passed": self.passed,
            },
            "conclusion": conclusion,
            "axes": [item.to_dict() for item in self.axes],
            "error": self.error,
        }

    def to_json(self, *, indent: int = 2) -> str:
        """Return the report as a JSON document."""

        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=False, sort_keys=True)

    def to_table(self) -> str:
        """Return the report as a human readable table.

        The table is what an operator reads first: one line per axis, the
        verdict, and -- for a failed axis -- the first field that
        disagreed with both values.
        """

        lines: list[str] = []
        header = f"{'AXIS':<16} {'VERDICT':<12} {'ASSERTED':>8} {'MISMATCHED':>10}  DETAIL"
        lines.append(header)
        lines.append("-" * len(header))
        for item in self.axes:
            detail = ""
            if item.mismatches:
                first = item.mismatches[0]
                detail = (
                    f"{first.field}: profile={_render(first.expected)} "
                    f"browser={_render(first.actual)}"
                )
            lines.append(
                f"{item.axis:<16} {item.verdict:<12} {item.asserted:>8} "
                f"{item.mismatched:>10}  {detail}"
            )
        counts = self.counts()
        lines.append("-" * len(header))
        lines.append(
            f"{'TOTAL':<16} {'':<12} {len(self.axes):>8} {counts['fail']:>10}  "
            f"pass={counts['pass']} fail={counts['fail']} unavailable={counts['unavailable']}"
        )
        return "\n".join(lines)


def _jsonable(value: Any) -> Any:
    """Return a JSON-serialisable rendering of ``value``."""

    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, Mapping):
        return {str(k): _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    return str(value)


def _render(value: Any) -> str:
    """Render a value for a one-line diagnostic."""

    text = json.dumps(_jsonable(value), sort_keys=True, separators=(",", ":"))
    if len(text) > 90:
        text = text[:87] + "..."
    return text


