#: The absolute path of the checked-in verification harness.
VERIFY_HARNESS_PATH: Path = Path(__file__).resolve().parent / "verify_harness.html"

#: The axes the harness checks, in the order it reports them.
VERIFY_AXES: Final[tuple[str, ...]] = (
    "navigator",
    "client_hints",
    "screen",
    "viewport",
    "timezone",
    "storage",
    "media_devices",
    "canvas",
    "audio",
    "rects",
    "webgl",
    "webgpu",
    "permissions",
    "battery",
    "fonts",
    "sensors",
    "media_queries",
    "geolocation",
    "math_precision",
    "heap",
    "media_decode",
)

#: The axes whose values come from the machine the browser runs on.
#:
#: A profile describes a device.  The machine that runs the verification
#: is a *different* device -- it has its own graphics card, its own
#: audio hardware, its own sensors, its own idea of where the user is.
#: So an axis that reads those values cannot agree with the profile,
#: and the disagreement says nothing about the profile.
#:
#: These axes are still reported, because an operator has to see them.
#: They are reported as ``host-dependent`` rather than as a failure,
#: and they are excluded from the pass rate: counting them would mean
#: measuring the verification machine instead of the product.
HOST_DEPENDENT_AXES: Final[frozenset[str]] = frozenset(
    {
        # The graphics card decides the vendor, the renderer and the
        # shading language, and whether there is an adapter at all.
        "webgl",
        "webgpu",
        # The sound card decides the sample rate.
        "audio",
        # The accelerometers of the machine decide the readings.
        "sensors",
        # The machine decides whether a location is known and whether
        # the page is allowed to ask for one.
        "geolocation",
        # The fonts of the machine decide the metrics, and the metrics
        # of a font the machine does not carry are the fallback's.
        "fonts",
    }
)

#: The verdict of a single axis.
AxisVerdict = str

#: The expression that runs the harness and returns its report.
VERIFY_EXPRESSION: Final[str] = (
    "window.__NOVA_VERIFY__ && typeof window.__NOVA_VERIFY__.run === 'function'"
    " ? window.__NOVA_VERIFY__.run() : Promise.resolve({ error: 'harness-missing' })"
)

#: The expression that reports whether the harness page is ready.
READY_EXPRESSION: Final[str] = "window.__NOVA_VERIFY_READY__ === true"

#: A script that captures the pristine built-ins *before* the JavaScript
#: runtime is installed.
#:
#: The runtime replaces prototype accessors with its own overrides and
#: hides them behind a ``Proxy`` that answers ``toString`` with the
#: native source text.  A page therefore cannot tell a substituted
#: accessor from a stock one by inspecting the source -- it can only tell
#: by comparing against the original function object.
#:
#: This script therefore records the identity of the built-ins at
#: document start, before the runtime runs, and publishes them on
#: ``window.__NOVA_PRISTINE__``.  The harness then uses the identity
#: comparison to decide whether an accessor was substituted.
PRISTINE_CAPTURE_SCRIPT: Final[str] = """
(function () {
  var out = {};
  try {
    if (typeof Element !== 'undefined') {
      out.getBoundingClientRect = Element.prototype.getBoundingClientRect;
      out.getClientRects = Element.prototype.getClientRects;
    }
  } catch (e) { /* ignore */ }
  try {
    if (typeof CanvasRenderingContext2D !== 'undefined') {
      out.getImageData = CanvasRenderingContext2D.prototype.getImageData;
    }
  } catch (e) { /* ignore */ }
  try {
    if (typeof Range !== 'undefined') {
      out.rangeGetBoundingClientRect = Range.prototype.getBoundingClientRect;
    }
  } catch (e) { /* ignore */ }
  try {
    if (navigator && navigator.gpu && navigator.gpu.requestAdapter) {
      out.requestAdapter = navigator.gpu.requestAdapter;
    }
  } catch (e) { /* ignore */ }
  try {
    if (navigator && navigator.userAgentData) {
      out.userAgentData = navigator.userAgentData;
      out.userAgentDataBrands = navigator.userAgentData.brands;
    }
  } catch (e) { /* ignore */ }
  try {
    if (navigator && navigator.mediaDevices && navigator.mediaDevices.enumerateDevices) {
      out.enumerateDevices = navigator.mediaDevices.enumerateDevices;
    }
  } catch (e) { /* ignore */ }
  try {
    if (window.performance && performance.memory) {
      out.jsHeapSizeLimit = performance.memory.jsHeapSizeLimit;
    }
  } catch (e) { /* ignore */ }
  try {
    window.__NOVA_PRISTINE__ = out;
  } catch (e) { /* ignore */ }
})();
""".strip()


