@dataclass
class _BrowserProcess:
    """A launched browser and the DevTools port it reported."""

    process: subprocess.Popen[bytes]
    port: int
    user_data_dir: Path


class VerifyRunner:
    """Runs the verification of a profile against a real browser.

    The runner performs five steps:

    1. build the JavaScript runtime of the profile;
    2. launch a Chromium-based browser with a temporary profile;
    3. attach over the DevTools protocol and install the runtime
       *before* the first navigation, so that the profile is present at
       ``document_start``;
    4. navigate to the verification harness and read its report;
    5. lift the report into :class:`VerifyReport`.

    The browser-facing parts are reachable through explicit injection
    points, so the tests can drive the runner without a browser.
    """

    def __init__(
        self,
        config: ProfileConfig,
        *,
        browser_path: str | None = None,
        headless: bool = True,
        timeout: float = 60.0,
        browser_finder: Any = find_browser,
        runtime_script: str | None = None,
    ) -> None:
        self._config = config
        self._browser_path = browser_path
        self._headless = headless
        self._timeout = timeout
        self._browser_finder = browser_finder
        self._runtime_script = runtime_script

    # -- the public entry point -------------------------------------------

    async def run(self) -> VerifyReport:
        """Run the whole verification and return the report."""

        try:
            browser_path = self._browser_finder(self._browser_path)
        except (BrowserNotFoundError, FileNotFoundError) as exc:
            return self._failure(str(exc))

        script = self._runtime_script
        if script is None:
            try:
                script = build_script(self._config)
            except Exception as exc:  # pragma: no cover - defensive
                return self._failure(f"the runtime could not be built: {exc}")

        launched: _BrowserProcess | None = None
        client: DevToolsClient | None = None
        session_id: str | None = None
        try:
            launched = await asyncio.to_thread(self._launch, browser_path)
            version = await asyncio.to_thread(
                self._fetch_json, f"http://127.0.0.1:{launched.port}/json/version"
            )
            ws_url = str(version.get("webSocketDebuggerUrl", ""))
            if not ws_url:
                return self._failure("the browser did not report a websocket debugger URL")

            client = DevToolsClient(ws_url, timeout=self._timeout)
            await client.connect()

            target = await client.send("Target.createTarget", {"url": "about:blank"})
            target_id = target.get("targetId")
            if not isinstance(target_id, str):
                return self._failure("Target.createTarget did not return a targetId")
            attached = await client.send(
                "Target.attachToTarget", {"targetId": target_id, "flatten": True}
            )
            raw_session = attached.get("sessionId")
            session_id = raw_session if isinstance(raw_session, str) else None

            await client.send("Page.enable", session_id=session_id)
            await client.send("Runtime.enable", session_id=session_id)

            # The pristine built-ins are captured *first*, so that the
            # harness can tell a substituted accessor from a stock one
            # by identity.  The runtime hides its overrides behind a
            # proxy that reports the native source text, so source
            # inspection cannot be used.
            await client.add_script_to_evaluate_on_new_document(
                PRISTINE_CAPTURE_SCRIPT, session_id=session_id
            )

            # The runtime has to be installed *before* the first
            # navigation, otherwise the harness would measure the stock
            # browser and never see the profile at all.
            await client.add_script_to_evaluate_on_new_document(
                script, session_id=session_id
            )

            url = VERIFY_HARNESS_PATH.resolve().as_uri()
            await client.send("Page.navigate", {"url": url}, session_id=session_id)
            await self._await_ready(client, session_id)

            payload = await client.evaluate(VERIFY_EXPRESSION, session_id=session_id)
            if not isinstance(payload, Mapping):
                return self._failure("the harness did not return a JSON object")
            if payload.get("error"):
                return self._failure(str(payload.get("error")))

            axes = _parse_axis_results(payload)
            passed = all(item.verdict != "fail" for item in axes)
            return VerifyReport(
                profile_id=self._config.identity.id,
                passed=passed,
                axes=axes,
                browser=browser_path,
                browser_version=str(version.get("Browser", "")),
                harness=url,
                has_runtime=bool(payload.get("hasRuntime")),
                has_native_core=bool(payload.get("hasNativeCore")),
            )
        except Exception as exc:
            return self._failure(f"{type(exc).__name__}: {exc}")
        finally:
            if client is not None:
                with contextlib.suppress(Exception):
                    await client.close()
            if launched is not None:
                await asyncio.to_thread(self._terminate, launched)

    def run_sync(self) -> VerifyReport:
        """Run the verification from synchronous code."""

        return asyncio.run(self.run())

    # -- internals ---------------------------------------------------------

    def _failure(self, message: str) -> VerifyReport:
        """Return a report that records a hard failure."""

        return VerifyReport(
            profile_id=self._config.identity.id,
            passed=False,
            axes=[],
            browser=str(self._browser_path or ""),
            error=message,
        )

    def _launch(self, browser_path: str) -> _BrowserProcess:
        """Launch the browser and return the process and its DevTools port."""

        user_data_dir = Path(tempfile.mkdtemp(prefix="nova-verify-"))
        command = [browser_path]
        if self._headless:
            command.append("--headless=new")
        command.append("--remote-debugging-port=0")
        command.append(f"--user-data-dir={user_data_dir}")
        command.append("--no-first-run")
        command.append("--no-default-browser-check")
        command.append("--disable-background-networking")
        command.append("--disable-sync")
        command.append("--disable-extensions")
        command.append("--disable-dev-shm-usage")
        command.append("--hide-scrollbars")
        command.append("--mute-audio")
        command.append("about:blank")
        process = subprocess.Popen(  # noqa: S603 - explicit, local binary
            command,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        try:
            port = self._read_devtools_port(user_data_dir)
        except Exception:
            self._terminate_process_tree(process)
            with contextlib.suppress(OSError):
                shutil.rmtree(user_data_dir, ignore_errors=True)
            raise
        return _BrowserProcess(process=process, port=port, user_data_dir=user_data_dir)

    @staticmethod
    def _read_devtools_port(user_data_dir: Path, timeout: float = 30.0) -> int:
        """Read the DevTools port Chrome wrote into ``DevToolsActivePort``."""

        port_file = user_data_dir / "DevToolsActivePort"
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if port_file.exists():
                try:
                    content = port_file.read_text(encoding="utf-8").splitlines()
                except OSError:  # pragma: no cover - transient
                    content = []
                if content:
                    try:
                        return int(content[0].strip())
                    except ValueError:  # pragma: no cover - transient
                        pass
            time.sleep(0.05)
        raise TimeoutError("the browser did not report a DevTools port in time")

    @staticmethod
    def _terminate(process: _BrowserProcess) -> None:
        """Terminate the browser and remove the temporary profile."""

        VerifyRunner._terminate_process_tree(process.process)
        shutil.rmtree(process.user_data_dir, ignore_errors=True)

    @staticmethod
    def _terminate_process_tree(process: subprocess.Popen[bytes]) -> None:
        """Terminate the browser *and* every child it spawned."""

        children: list[Any] = []
        try:
            import psutil

            parent = psutil.Process(process.pid)
            children = parent.children(recursive=True)
        except Exception:  # pragma: no cover - psutil optional at runtime
            children = []

        with contextlib.suppress(Exception):
            process.terminate()
        with contextlib.suppress(Exception):
            process.wait(timeout=10)

        for child in children:
            with contextlib.suppress(Exception):
                child.terminate()
        for child in children:
            with contextlib.suppress(Exception):
                child.wait(timeout=5)
            with contextlib.suppress(Exception):
                if child.is_running():
                    child.kill()

        if process.poll() is None:  # pragma: no cover - stubborn process
            with contextlib.suppress(Exception):
                process.kill()
            with contextlib.suppress(Exception):
                process.wait(timeout=5)

    @staticmethod
    def _fetch_json(url: str) -> dict[str, Any]:
        """Fetch a JSON document from the local DevTools endpoint."""

        import urllib.request

        with urllib.request.urlopen(url, timeout=10) as response:  # noqa: S310 - loopback only
            payload = json.loads(response.read().decode("utf-8"))
        return payload if isinstance(payload, dict) else {}

    async def _await_ready(self, client: DevToolsClient, session_id: str | None) -> None:
        """Wait until the verification harness is installed in the page."""

        deadline = time.monotonic() + self._timeout
        while time.monotonic() < deadline:
            try:
                ready = await client.evaluate(READY_EXPRESSION, session_id=session_id)
            except Exception:
                ready = False
            if ready:
                return
            await asyncio.sleep(0.1)
        raise TimeoutError("the verification harness did not initialise in time")


