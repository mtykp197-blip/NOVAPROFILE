"""Verification of a generated profile against a **real** browser.

The whole point of this module
------------------------------

The control plane generates a profile; the browser core is supposed to
present that profile to the page.  Everything else in the project --
the simulator, the probe, the collision guard -- checks the profile
against the *model*.  This module checks the profile against the
*browser*: it starts a stock Chrome, installs the profile's JavaScript
runtime at ``document_start``, loads an independent harness page, and
compares what the profile declares against what the browser actually
reports.

A disagreement is not a cosmetic difference.  It means the profile the
control plane hands to the core is not the profile the page sees.

How it works
------------

    10|1. The harness page (:data:`VERIFY_HARNESS_PATH`) is a *static,
  self-contained* HTML file.  It reads the profile out of
  ``window.__NOVA_PROFILE__`` (the payload the JavaScript runtime
  installs) and the browser out of the live accessors, and publishes the
  comparison on ``window.__NOVA_VERIFY__``.
2. The runtime is installed with ``Page.addScriptToEvaluateOnNewDocument``
  so that it is present before the harness' first script runs.
3. The harness is evaluated over the DevTools protocol and its JSON
  report is compared against the expectations derived from the profile.

Why the harness is a separate file
----------------------------------

The harness must not be generated by the code it verifies.  A harness
built from the same table that produces the profile can only prove that
the two are self-consistent.  The harness is therefore a hand-written,
checked-in page that reads the browser with the accessors a
fingerprinting script would use -- ``navigator.userAgent``,
``gl.getParameter(gl.MAX_TEXTURE_SIZE)``, ``canvas.toDataURL()`` -- and
that reads the profile out of the object the runtime publishes.

The axes
--------

Twenty-one axes are checked::

    navigator, client_hints, screen, viewport, timezone, storage,
    media_devices, canvas, audio, rects, webgl, webgpu, permissions,
    battery, fonts, sensors, media_queries, geolocation, math_precision,
    heap, media_decode

Every axis is compared field by field.  A field whose profile value is
``null`` is *not asserted* -- the profile does not describe it -- but it
is still measured and reported.
"""

