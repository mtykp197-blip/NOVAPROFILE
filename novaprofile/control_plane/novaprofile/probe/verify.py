def _parse_axis_results(payload: Mapping[str, Any]) -> list[AxisResult]:
    """Turn the harness payload into the per-axis results.

    The harness does the comparison itself -- it is the component that
    knows how a fingerprinting script reads each surface -- and this
    function only *verifies the shape* of the answer and lifts it into
    the dataclasses the report is built from.

    An axis the harness did not report is reported as ``unavailable``
    rather than silently dropped: a missing axis is a fact an operator
    has to see.
    """

    results: list[AxisResult] = []
    raw_axes = payload.get("axes")
    if not isinstance(raw_axes, list):
        raw_axes = []

    by_name: dict[str, Mapping[str, Any]] = {}
    for item in raw_axes:
        if isinstance(item, Mapping):
            name = item.get("axis")
            if isinstance(name, str):
                by_name[name] = item

    for axis in VERIFY_AXES:
        raw = by_name.get(axis)
        if raw is None:
            results.append(
                AxisResult(axis=axis, verdict="unavailable", asserted=0, mismatched=0)
            )
            continue
        verdict = str(raw.get("verdict", "unavailable"))
        # An axis whose values come from the machine cannot disagree
        # with the profile in any meaningful way, so it is labelled
        # rather than counted as a failure.  The fields are still kept:
        # an operator wants to see what the host actually reported.
        if verdict == "fail" and axis in HOST_DEPENDENT_AXES:
            verdict = "host-dependent"
        fields: list[FieldVerdict] = []
        raw_fields = raw.get("fields")
        if isinstance(raw_fields, list):
            for item in raw_fields:
                if not isinstance(item, Mapping):
                    continue
                fields.append(
                    FieldVerdict(
                        field=str(item.get("field", "")),
                        verdict=str(item.get("verdict", "match")),
                        expected=item.get("expected"),
                        actual=item.get("actual"),
                        detail=str(item.get("detail", "")),
                    )
                )
        results.append(
            AxisResult(
                axis=axis,
                verdict=verdict,
                asserted=int(raw.get("asserted", 0) or 0),
                mismatched=int(raw.get("mismatched", 0) or 0),
                fields=tuple(fields),
                profile=raw.get("profile"),
                browser=raw.get("browser"),
            )
        )
    return results


