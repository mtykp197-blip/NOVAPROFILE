"""Generates the C++ resource that holds the JavaScript layer's code.

The layer is two parts: the *code*, which is the same for every profile,
and the *payload*, which carries the profile's values.

The code is seventy-five kilobytes.  It is compiled into the browser
instead of being handed over at run time, because a Windows command
line holds at most 32,767 characters and the payload alone is already
ten kilobytes of base64.  Shipping the code through the same channel
would either not fit or would have to be compressed, and a compressed
argument is a thing that has to be decompressed before it can be read
-- which is one more place for the hand-over to go wrong.

The payload stays on the command line.  It is small, it is different
for every profile, and it is the only part that is secret.

The file is generated, not written by hand: the code lives in the
control plane, in one place, and this script copies it into the
Chromium tree so that the two cannot drift apart.

Usage::

    python -m novaprofile.js_runtime.generate_native_resource \\
        --output C:/chromium/src/third_party/blink/renderer/core/nova/nova_js_runtime_code.cc
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from .builder import RUNTIME_JS

#: The header of the generated file.
#:
#: The runtime code is a string literal, and a string literal cannot
#: hold a NUL.  The code has none -- it is JavaScript -- but the check
#: is here because a NUL would silently truncate it.
_HEADER = """// Generated file.  Do not edit.
//
// The JavaScript layer's code, compiled into the browser.  It is the
// same for every profile; only the payload differs, and that travels
// separately.
//
// The file is generated by:
//   novaprofile.js_runtime.generate_native_resource
//
// The source of truth is novaprofile/js_runtime/builder.py.

#include "third_party/blink/renderer/core/nova/nova_chromium_hooks.h"

namespace nova {
namespace {

// The layer's code.
//
// It is stored as a string literal because that is what it is: a piece
// of JavaScript that the renderer compiles and runs at the start of
// every document.
const char kJsRuntimeCode[] = R"NOVAJS(
%s)NOVAJS";

}  // namespace

// The layer's code, as a string.
const std::string& GetJsRuntimeCode() {
  static const std::string* code = new std::string(kJsRuntimeCode);
  return *code;
}

}  // namespace nova
"""


def generate(output: Path) -> int:
    """Write the generated file to ``output``.

    Returns the number of bytes written.
    """

    if "\0" in RUNTIME_JS:
        raise ValueError("the runtime code holds a NUL and cannot be a literal")

    output.parent.mkdir(parents=True, exist_ok=True)
    text = _HEADER % RUNTIME_JS
    output.write_text(text, encoding="utf-8", newline="\n")
    return len(text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="where to write the generated C++ file",
    )
    args = parser.parse_args(argv)

    written = generate(args.output)
    print(f"wrote {written} bytes to {args.output}")
    return 0


if __name__ == "__main__":  # pragma: no cover - the command line
    sys.exit(main())
