def _cutout_screen(
    width: int,
    height: int,
    dpr: float,
    density: int,
    color_depth: int = 24,
) -> Screen:
    """A screen whose available area is inset, as on a curved panel."""

    return Screen(
        width=width,
        height=height,
        avail_width=width,
        avail_height=height - 48,
        avail_left=0,
        avail_top=0,
        color_depth=color_depth,  # type: ignore[arg-type]
        pixel_depth=color_depth,  # type: ignore[arg-type]
        device_pixel_ratio=dpr,  # type: ignore[arg-type]
        density_dpi=density,
    )


