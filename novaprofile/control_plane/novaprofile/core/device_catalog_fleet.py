"""The extended fleet catalogue, part two.

This module continues :mod:`novaprofile.core.device_catalog_extended`.
Together the three catalogues hold the whole fleet:

* :mod:`novaprofile.core.devices` -- the eleven reference devices that
  the test suite was written against;
* :mod:`novaprofile.core.device_catalog_extended` -- thirty-one more;
* this module -- eighty-nine more.

The fleet has to grow with the number of users behind the product.  A
vendor that groups on the model string puts every profile of a fleet of
forty-two devices into forty-two buckets, which is separable at the
first glance.  A fleet of one hundred and three devices gives every
vendor three times as many buckets to separate, and the marginal cost of
one more device is a single entry in this file.

The rules the entries follow are the rules of the reference fleet:

* every SoC pairs with the GPU that actually ships inside it -- a
  Snapdragon 7+ Gen 2 brings an Adreno 732, a Dimensity 9200 brings an
  Immortalis-G715, a Tensor G2 brings a Mali-G710;
* every screen matches the panel the model really has -- the resolution,
  the density bucket and the device pixel ratio are the ones the
  hardware reports;
* the Android release, the SDK level, the security patch and the build
  identifier agree with each other and with the era of the device;
* the board, the product and the device codenames are the ones the
  build fingerprint carries.

The GPU profiles that are not in :mod:`novaprofile.core.devices` are
declared here.  They follow the same shape: the unmasked vendor and
renderer strings that the driver reports, the WebKit vendor and renderer
that Chromium substitutes, and the parameter table that the hardware
really has -- a budget GPU reports an 8192 texture limit where a
flagship reports 16384, and a site that reads ``MAX_TEXTURE_SIZE``
sees that difference.
"""

