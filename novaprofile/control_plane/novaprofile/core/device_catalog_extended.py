"""The extended device catalogue.

The core catalogue in :mod:`novaprofile.core.devices` holds the eleven
devices that the whole test suite was written against.  They are the
*reference* fleet: every consistency rule has an example to check
itself against.

But eleven devices is not a fleet.  Eleven devices means eleven model
strings, eleven boards, eleven build identifiers -- and a vendor that
groups on any of them puts every profile of the fleet into one of
eleven buckets.  With tens of thousands of users behind the product,
the number of buckets has to grow with the number of users, or the
whole fleet is trivially separable.

This module holds the additional devices.  They follow the same rules
as the reference ones:

* every SoC pairs with the GPU that actually ships inside it,
* every screen matches the panel the model really has,
* the Android release, the SDK level and the security patch agree with
  each other and with the era of the device.

The catalogue is deliberately built from *combinations that ship*: a
Snapdragon 8 Gen 2 always brings an Adreno 740, and an Exynos 2400
always brings an Xclipse 940.  A profile that pairs them wrongly is a
profile that a site can catch by cross-checking the renderer against
the architecture the client hints advertise.
"""

